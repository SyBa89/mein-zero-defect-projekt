/**
 * Konvertiert einen Wert sicher in einen String.
 * @param value - Der zu konvertierende Wert.
 * @returns Ein String oder leerer String.
 */
export function safeString(value: unknown): string {
  if (typeof value === 'string') return value;
  if (typeof value === 'number') return String(value);
  return '';
}

/**
 * Konvertiert einen Wert sicher in einen Boolean.
 * @param value - Der zu konvertierende Wert.
 * @returns Boolean oder false.
 */
export function safeBoolean(value: unknown): boolean {
  return typeof value === 'boolean' ? value : false;
}

export function safeNumber(value: unknown): number {
  if (typeof value === 'number') return value;
  if (typeof value === 'string') return parseFloat(value) || 0;
  return 0;
}

